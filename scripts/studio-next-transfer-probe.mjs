import assert from "node:assert/strict";
import {readFile,mkdir,writeFile} from "node:fs/promises";
import {resolve,dirname} from "node:path";
import {fileURLToPath} from "node:url";
import {createAccount,createClient,isSuccessful} from "genlayer-js";
import {studioDevnet} from "genlayer-js/chains";

const endpoint=process.env.GENLAYER_RPC_URL||"https://studio-next.genlayer.com/api";
const chain={...studioDevnet,name:"GenLayer Studio Next",rpcUrls:{default:{http:[endpoint]}}};
assert.equal(chain.id,61997,"Studio Next chain guard");
const root=resolve(dirname(fileURLToPath(import.meta.url)),"..");
const env=Object.fromEntries((await readFile(resolve(root,".env"),"utf8")).split(/\r?\n/).flatMap(line=>{const match=line.match(/^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/);if(!match)return[];let value=match[2].trim();if((value.startsWith('"')&&value.endsWith('"'))||(value.startsWith("'")&&value.endsWith("'")))value=value.slice(1,-1);return[[match[1],value]];}));
assert.ok(env.PRIVATE_KEY,"PRIVATE_KEY is required");
const privateKey=env.PRIVATE_KEY.startsWith("0x")?env.PRIVATE_KEY:`0x${env.PRIVATE_KEY}`;
const account=createAccount(privateKey);
const client=createClient({chain,endpoint,account});
const contractPath=process.argv[2] ? resolve(root,process.argv[2]) : new URL("../contracts/studio_next_transfer_probe.py",import.meta.url);
const code=new Uint8Array(await readFile(contractPath));
const report={version:"studio-next-transfer-probe-1",network:"studio-next",chainId:chain.id,account:account.address,startedAt:new Date().toISOString(),steps:{}};
await client.initializeConsensusSmartContract();
const estimate=await client.estimateTransactionFees();
report.steps.deploy={feeValue:String(estimate.feeValue),distribution:Object.fromEntries(Object.entries(estimate.distribution).map(([key,value])=>[key,Array.isArray(value)?value.map(String):String(value)]))};
const deployRequest={code,args:[]};
if(process.env.PROBE_NO_FEES!=="1")deployRequest.fees={distribution:estimate.distribution,feeValue:estimate.feeValue};
const hash=await client.deployContract(deployRequest);
report.steps.deploy.hash=hash;
const receipt=await client.waitForTransactionReceipt({hash,waitUntil:"finalized",retries:240,interval:1000});
report.steps.deploy.receipt=receipt;
await mkdir(new URL("../reports/studio-next-transfer-probe/",import.meta.url),{recursive:true});
await writeFile(new URL("../reports/studio-next-transfer-probe/deploy.json",import.meta.url),JSON.stringify(report,null,2));
assert.equal(isSuccessful(receipt),true,"Probe deployment execution failed");
const address=receipt.txDataDecoded?.contractAddress ?? receipt.data?.contract_address;
assert.match(address,/^0x[0-9a-fA-F]{40}$/,"Missing probe contract address");
report.contract=address;
report.finishedAt=new Date().toISOString();
await writeFile(new URL("../reports/studio-next-transfer-probe/deploy.json",import.meta.url),JSON.stringify(report,null,2));
console.log(JSON.stringify({passed:true,chainId:chain.id,contract:address,hash}));
